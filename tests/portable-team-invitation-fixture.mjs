import assert from 'node:assert/strict';

export async function verifyTeamInvitation({request,origin,owner,backup,rep,repEmail,backupEmail,backupId,manage,change,read,workspaceId,sql}){
  const department=crypto.randomUUID(),foreign=crypto.randomUUID(),root=crypto.randomUUID(),pod=crypto.randomUUID(),base='/api/workspaces';
  const ownerChange=async body=>read(await change(owner,body));
  await ownerChange({action:'team_create',id:department,name:'Sales',parentId:null});
  await ownerChange({action:'team_create',id:root,name:'Client services',parentId:department});
  await ownerChange({action:'team_create',id:pod,name:'Renewals',parentId:root});
  const sibling=crypto.randomUUID(),subpod=crypto.randomUUID();
  await ownerChange({action:'team_create',id:sibling,name:'Account sales',parentId:department});
  await ownerChange({action:'team_create',id:subpod,name:'East',parentId:pod});
  await ownerChange({action:'team_assign',id:backupId,teamId:subpod,previousTeamId:null});
  const [{id:repOwner}]=await sql`SELECT id FROM login_identities WHERE email=${backupEmail}`;
  async function deal(name,assigneeId){
    const response=await change(owner,{action:'save',kind:'deals',data:{name},assigneeId},'/api/crm');
    assert.equal(response.status,201,await response.clone().text());
    return (await response.json()).record.id;
  }
  const teamDeal=await deal('Fictional renewal',repOwner),outside=await deal('Unassigned prospect',null);
  const invite={action:'invite',email:repEmail,teamId:root,role:'viewer',viewScope:'team',editScope:'team'};
  await read(await change(backup,{action:'team_create',id:foreign,name:'Sales',parentId:null}));
  assert.equal((await manage({...invite,teamId:foreign})).status,409);
  await read(await change(backup,{action:'team_remove',id:foreign,revision:1}));
  const delegated=(await read(await manage(invite))).sent.find(i=>i.email===repEmail);
  assert.equal(delegated.teamName,'Client services');
  assert.equal((await read(await manage(invite))).sent.find(i=>i.email===repEmail).id,delegated.id);
  assert.equal((await manage({...invite,teamId:pod})).status,409);
  const roleChange=(await read(await manage({action:'invite_role',id:delegated.id,role:'editor'}))).sent.find(i=>i.email===repEmail);
  const policy={action:'standardAccess',kind:'deals',id:'amount'};
  await read(await change(owner,{...policy,audience:root,expectedRevision:0},'/api/custom-properties'));
  assert.equal((await change(rep,{action:'accept_invite',id:roleChange.id})).status,409);
  assert.ok((await read(await request(base,{headers:owner}))).sent.some(row=>row.id===roleChange.id));
  assert.equal((await manage({action:'invite_role',id:roleChange.id,role:'viewer'})).status,409);
  await ownerChange({action:'cancel_invite',id:roleChange.id});
  assert.equal((await manage(invite)).status,409);
  const {chromium}=await import(process.env.HARBOR_TEST_PLAYWRIGHT??'playwright');
  const browser=await chromium.launch({executablePath:process.env.HARBOR_TEST_CHROME});
  async function open(auth,path){
    const context=await browser.newContext();
    const [name,value]=auth.cookie.split('=');
    await context.addCookies([{name,value,url:origin}]);
    const page=await context.newPage();
    await page.goto(origin+path);
    return page;
  }
  try{
    const withUnassigned=await ownerChange({action:'invite',role:'viewer',email:repEmail});
    const unassigned=withUnassigned.sent.find(i=>i.email===repEmail);
    const page=await open(owner,'/?view=workspaces#invite-teammate');
    const filter=page.getByRole('combobox',{name:'Filter by primary team'});
    const includeChildren=page.getByRole('checkbox',{name:'Include child teams'});
    const active=email=>page.locator('.portable-access-member > summary').filter({hasText:email});
    const pending=email=>page.locator('.portable-access-invitation').filter({hasText:email});
    await filter.selectOption('unassigned');
    assert.ok(await pending(repEmail).isVisible());
    assert.equal(await active(backupEmail).count(),0);
    await ownerChange({action:'cancel_invite',id:unassigned.id});
    const form=page.locator('#invite-teammate').locator('form').filter({has:page.getByRole('button',{name:'Prepare invitation'})});
    await form.getByRole('textbox',{name:'Teammate email'}).fill(repEmail);
    await form.getByRole('combobox',{name:/Primary team/}).selectOption(root);
    await form.getByRole('combobox',{name:/Can view/}).selectOption('team');
    await form.getByRole('button',{name:'Prepare invitation'}).click();
    await page.locator('.portable-access-invitation').filter({hasText:repEmail}).getByText('Team: Sales / Client services',{exact:false}).waitFor();
    await filter.selectOption(root);
    assert.ok(await pending(repEmail).isVisible());
    await filter.selectOption('unassigned');
    await page.getByText('No teammates or invitations match these filters.').waitFor();
    await filter.selectOption(root);
    await active(backupEmail).getByText('Sales / Client services / Renewals / East').waitFor();
    await includeChildren.uncheck();
    assert.equal(await active(backupEmail).count(),0);
    assert.ok(await pending(repEmail).isVisible());
    await includeChildren.check();
    await page.getByRole('searchbox',{name:'Find a teammate'}).fill(repEmail);
    assert.ok(await pending(repEmail).isVisible());
    assert.equal(await active(backupEmail).count(),0);
    await page.getByRole('button',{name:'Clear search'}).click();
    await active(backupEmail).waitFor();
    const sent=(await read(await request(base,{headers:owner}))).sent.find(i=>i.email===repEmail);
    assert.equal(sent.teamName,'Client services');
    const link=id=>'/api/crm?kind=deals&id='+id+'&workspaceId='+workspaceId;
    assert.equal((await request(link(teamDeal),{headers:rep})).status,404);
    const review=await open(rep,'/?invitation='+sent.id);
    await review.getByText('Primary team: Sales / Client services').waitFor();
    await review.getByRole('button',{name:'Accept invitation'}).click();
    await review.waitForURL(u=>u.searchParams.get('workspaceId')===workspaceId);
    const joined=(await read(await request(base,{headers:owner}))).viewers.find(m=>m.email===repEmail);
    assert.equal(joined.teamId,root);
    await page.getByRole('button',{name:'Refresh sharing'}).click();
    await active(repEmail).waitFor();
    assert.equal(await pending(repEmail).count(),0);
    assert.equal((await request(link(teamDeal),{headers:rep})).status,200);
    assert.equal((await request(link(outside),{headers:rep})).status,404);
    // The manager keeps the same session and grant while the record owner's whole branch moves.
    await page.getByText(/^Teams and pods/).click();
    const choose=page.getByRole('combobox',{name:'Manage team',exact:true});
    await choose.selectOption(pod);
    const parent=page.getByRole('combobox',{name:'Parent team',exact:true});
    const preview=page.getByRole('region',{name:'Record access after move'});
    const move=page.getByRole('button',{name:'Save team',exact:true});
    await parent.selectOption(sibling);
    assert.equal(await preview.locator('p').filter({hasText:'Gain team access'}).innerText(),'Gain team access · Sales / Account sales');
    assert.equal(await preview.locator('p').filter({hasText:'Lose team access'}).innerText(),'Lose team access · Sales / Client services');
    assert.equal((await request(link(teamDeal),{headers:rep})).status,200);
    await move.click();
    await preview.waitFor({state:'hidden'});
    assert.equal((await request(link(teamDeal),{headers:rep})).status,404);
    assert.equal(await active(backupEmail).count(),0);
    assert.ok(await active(repEmail).isVisible());
    await parent.selectOption(root);
    await preview.getByText('Gain team access · Sales / Client services').waitFor();
    await move.click();
    await preview.waitFor({state:'hidden'});
    assert.equal((await request(link(teamDeal),{headers:rep})).status,200);
    assert.equal((await request(link(outside),{headers:rep})).status,404);
    await active(backupEmail).getByText('Sales / Client services / Renewals / East').waitFor();
    await ownerChange({action:'revoke',id:joined.id});
    assert.equal((await request(link(teamDeal),{headers:rep})).status,404);
  }finally{await browser.close();}
  await read(await change(owner,{...policy,audience:'workspace',expectedRevision:1},'/api/custom-properties'));
  await ownerChange({action:'team_assign',id:backupId,teamId:null,previousTeamId:subpod});
  await ownerChange({action:'team_remove',id:subpod,revision:1});
  await ownerChange({action:'team_remove',id:sibling,revision:1});
  const pending=(await ownerChange({...invite,teamId:pod})).sent.find(i=>i.email===repEmail);
  assert.equal((await change(owner,{action:'team_remove',id:pod,revision:3})).status,409);
  await sql`UPDATE portable_workspace_invites SET expires_at=now()-interval '1 minute' WHERE id=${pending.id}`;
  await ownerChange({action:'team_remove',id:pod,revision:3});
  await ownerChange({action:'team_remove',id:root,revision:1});
  await ownerChange({action:'team_remove',id:department,revision:1});
  assert.equal((await change(rep,{action:'accept_invite',id:pending.id})).status,404);
}
