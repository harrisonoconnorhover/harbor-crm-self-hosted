import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';

export async function verifyInboxArticle({origin,request,post,ok,other,workspaceId,id,deliveries,cannedReply}){
  const articles='/api/knowledge-base',pub=articles+'?publication=1',articleId=randomUUID();
  const config={action:'settings',name:'Field support',accent:'#235451',enabled:true,revision:0};
  const {center}=await ok(post(pub,config));
  const sentBefore=(await deliveries()).length;
  const content={title:'Pair the dock scanner',subtitle:'Field setup',category:'Private classification',tags:[],bodyHtml:'<p>Press the green pairing button.</p>'};
  await ok(post(articles,{action:'save',id:articleId,revision:0,content}));
  await ok(post(pub,{action:'publish',id:articleId,revision:0,articleRevision:1,topic:'Scanner setup'}));
  const returnId=randomUUID(),returnTitle='Return the scanner';
  await ok(post(articles,{action:'save',id:returnId,revision:0,content:{...content,title:returnTitle}}));
  await ok(post(pub,{action:'publish',id:returnId,revision:0,articleRevision:1,topic:'Returns'}));
  await ok(post(articles,{action:'save',id:articleId,revision:1,content:{...content,title:'Private draft of scanner guide',bodyHtml:'<p>Unreleased model number.</p>'}}));
  const url=origin+'/help/'+center.id+'/'+articleId;
  const library='/?view=knowledge&workspaceId='+workspaceId;
  const picker='/api/team-inbox?articles=1&workspaceId='+workspaceId;
  const directory='/api/team-inbox?articles=topics',sharedDirectory=directory+'&workspaceId='+workspaceId;
  const read=async path=>{
    const result=await request(path,{headers:other});
    assert.equal(result.status,200,path);
    return result.json();
  };
  assert.equal((await request(sharedDirectory)).status,401);
  assert.deepEqual((await read(directory)).topics,[]);
  assert.deepEqual((await read(sharedDirectory)).topics,['Returns','Scanner setup']);
  assert.deepEqual((await read(sharedDirectory+'&afterTopic=Returns')).topics,['Scanner setup']);
  const filtered=library+'&topic=Scanner+setup&q=scaner+green';
  const login=await request(filtered);
  assert.equal(login.status,307);
  assert.equal(new URL(login.headers.get('location'),origin).searchParams.get('return_to'),filtered);
  const privatePage=await request(library+'&article='+articleId,{headers:other});
  assert.equal(privatePage.status,404);
  assert.equal((await request(picker)).status,401);
  const personal=await (await request('/api/team-inbox?articles=1',{headers:other})).json();
  assert.equal(personal.center,null);
  const {chromium}=await import(process.env.HARBOR_TEST_PLAYWRIGHT??'playwright');
  const browser=await chromium.launch({executablePath:process.env.HARBOR_TEST_CHROME});
  try{
    const context=await browser.newContext({viewport:{width:390,height:844}});
    const [name,value]=other.cookie.split('=');
    await context.addCookies([{name,value,url:origin}]);
    const page=await context.newPage();
    await page.goto(origin+library);
    await page.getByRole('button',{name:'Filter by topic'}).click();
    const topic=page.getByLabel('Published topic',{exact:true});
    await topic.selectOption('Scanner setup');
    await page.getByLabel('Search published articles').fill('scaner green');
    await page.getByRole('button',{name:'Search',exact:true}).click();
    await page.getByRole('heading',{name:'Similar articles'}).waitFor();
    const link=page.getByRole('link',{name:content.title,exact:true});
    await link.waitFor();
    assert.equal(new URL(page.url()).searchParams.get('topic'),'Scanner setup');
    assert.equal(await page.getByRole('link',{name:returnTitle,exact:true}).count(),0);
    assert.equal(new URL(await link.getAttribute('href'),origin).href,url);
    const snippetReads=[];
    page.on('request',req=>{
      const params=new URL(req.url()).searchParams;
      if(params.has('snippets'))snippetReads.push(params);
    });
    await page.goto(origin+'/?view=team-inbox&workspaceId='+workspaceId+'&id='+id);
    const reply=page.getByLabel(/^Reply to /);
    await reply.fill('Here are the steps we discussed.');
    assert.equal(snippetReads.length,0);
    await page.getByText('Quick replies',{exact:true}).click();
    const find=page.getByLabel('Find a quick reply'),pick=page.getByLabel('Quick reply',{exact:true});
    await find.fill('No saved answer matches this');
    await page.getByText('No matching quick replies.',{exact:true}).waitFor();
    await find.fill('instructions');
    await pick.selectOption({label:cannedReply.name});
    await page.getByLabel('Quick reply preview').filter({hasText:cannedReply.body}).waitFor();
    assert.deepEqual(snippetReads.filter(params=>params.get('snippets')==='1').map(params=>params.get('id')),[cannedReply.id]);
    assert.equal(await reply.inputValue(),'Here are the steps we discussed.');
    await page.getByRole('button',{name:'Insert reply',exact:true}).click();
    assert.equal(await reply.inputValue(),'Here are the steps we discussed.\n\n'+cannedReply.body);
    assert.equal((await deliveries()).length,sentBefore);
    await page.getByText('Insert help article',{exact:true}).click();
    await page.getByRole('button',{name:'Filter by topic'}).click();
    await topic.selectOption('Returns');
    await page.getByRole('button',{name:'Insert '+returnTitle,exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'Insert '+content.title,exact:true}).count(),0);
    assert.equal(await reply.inputValue(),'Here are the steps we discussed.\n\n'+cannedReply.body);
    await topic.selectOption('Scanner setup');
    await page.getByLabel('Find a published article').fill('Unreleased model');
    await page.getByText('No matching published articles.',{exact:true}).waitFor();
    await page.getByLabel('Find a published article').fill('scaner green');
    await page.getByRole('heading',{name:'Similar articles'}).waitFor();
    await page.getByRole('button',{name:'Insert '+content.title}).click();
    const text='Here are the steps we discussed.\n\n'+cannedReply.body+'\n\n'+content.title+'\n'+url;
    assert.equal(await reply.inputValue(),text);
    assert.equal((await deliveries()).length,sentBefore,'Inserting a link must leave the reply unsent');
    await page.getByRole('button',{name:'Send reply',exact:true}).click();
    await page.getByText('Reply accepted for delivery.',{exact:true}).waitFor();
    assert.equal((await deliveries()).at(-1).payload.TextBody,text);
    const customer=await browser.newPage();
    await customer.goto(url);
    await customer.getByRole('heading',{name:content.title}).waitFor();
    assert.ok(!(await customer.locator('body').innerText()).includes('Unreleased'));
    await ok(post(pub,{action:'withdraw',id:articleId,articleRevision:2,revision:1}));
    assert.equal((await request(url.slice(origin.length))).status,404);
    assert.deepEqual((await read(sharedDirectory)).topics,['Returns']);
    const stale=await read(picker+'&topic=Scanner+setup');
    assert.equal(stale.center.name,config.name);
    assert.deepEqual(stale.items,[]);
    await ok(post(pub,{action:'withdraw',id:returnId,articleRevision:1,revision:1}));
    for(const q of ['', '&q=scaner+green'])assert.deepEqual((await (await request(picker+q,{headers:other})).json()).items,[]);
  }finally{await browser.close();}
}
