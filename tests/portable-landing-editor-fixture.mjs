import assert from 'node:assert/strict';

export async function verifyLandingEditor({headers,origin,custom,inlineForm,base,stopEmbedding,closeForm}){
  const {chromium}=await import(process.env.HARBOR_TEST_PLAYWRIGHT??'playwright');
  const browser=await chromium.launch({executablePath:process.env.HARBOR_TEST_CHROME});
  try{
    const context=await browser.newContext({viewport:{width:1440,height:1000}});
    const [name,value]=headers.cookie.split('=');
    await context.addCookies([{name,value,url:origin}]);
    const page=await context.newPage();
    const visitor=await browser.newPage({viewport:{width:1280,height:800}});
    const button=name=>page.getByRole('button',{name,exact:true});
    await page.goto(origin+'/?view=landing-pages&edit=new');
    await page.getByLabel('Page title').fill('November product clinic');
    await page.getByLabel('Page address').fill('product-clinic');
    await button('Add paragraph').dragTo(page.locator('.landing-drop-end'));
    await page.getByLabel('Paragraph text').fill('Send a question before the clinic.');
    const blocks=page.locator('.landing-block');
    await button('Add two columns').dragTo(blocks.first(),{targetPosition:{x:12,y:10}});
    const first=page.getByRole('group',{name:'First column',exact:true});
    const second=page.getByRole('group',{name:'Second column',exact:true});
    await first.getByLabel('Heading').fill('Morning session');
    await first.getByLabel('Paragraph').fill('Bring a sample pipeline.');
    await second.getByLabel('Heading').fill('Afternoon session');
    await second.getByLabel('Paragraph').fill('Practice the handoff.');
    assert.deepEqual(await blocks.locator('strong').allTextContents(),['Two columns','Paragraph']);
    await blocks.nth(1).locator('strong').dragTo(blocks.first(),{targetPosition:{x:12,y:10}});
    assert.deepEqual(await blocks.locator('strong').allTextContents(),['Paragraph','Two columns']);
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('combobox',{name:/Insert position/}).selectOption({label:'Before 2. Two columns'});
    await button('Add heading').focus();
    await page.keyboard.press('Enter');
    assert.ok(await page.getByLabel('Heading text').evaluate(el=>el===document.activeElement));
    await page.getByLabel('Heading text').fill('Choose a session');
    assert.deepEqual(await blocks.locator('strong').allTextContents(),['Paragraph','Heading','Two columns']);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'The mobile editor fits the viewport');
    await page.getByRole('combobox',{name:/Insert position/}).selectOption('');
    await button('Add lead form').click();
    await page.getByRole('combobox',{name:/^Lead form/}).selectOption(inlineForm);
    await page.getByLabel('Display form').selectOption('inline');
    await page.getByLabel('Form heading').fill('Register for the clinic');
    await page.getByRole('combobox',{name:/Insert position/}).selectOption({label:'Before 1. Paragraph'});
    await button('Add call to action').click();
    const signup=blocks.first();
    await signup.getByLabel('Button text').fill('Jump to registration');
    await signup.getByLabel('Button destination').selectOption('section');
    await signup.getByLabel('Page section').selectOption({label:'5. Lead form · Register for the clinic'});
    await page.getByRole('combobox',{name:/Insert position/}).selectOption('');
    await button('Add call to action').click();
    const booking=blocks.last();
    const bookingUrl='https://booking.example.test/demo?source=clinic&team=sales';
    await booking.getByLabel('Button text').fill('Book a demo');
    await booking.getByRole('textbox',{name:'Website address',exact:true}).fill(bookingUrl);
    const preview=page.frameLocator('iframe');
    await preview.getByText('Book a demo',{exact:true}).waitFor();
    assert.equal(await preview.getByRole('link',{name:'Book a demo'}).count(),0);
    await preview.getByRole('heading',{name:'Morning session'}).waitFor();
    await preview.getByText('Lead form preview · submissions disabled').waitFor();
    assert.equal(await preview.locator('iframe').count(),0);
    const address=page.getByLabel('Preview address');
    assert.deepEqual(await address.locator('option').allTextContents(),[custom,origin]);
    assert.equal(await address.inputValue(),custom);
    await address.selectOption(origin);
    await preview.locator('span.cta',{hasText:'Register for the clinic'}).waitFor();
    assert.equal(await preview.locator('.lead-capture, a, iframe, script').count(),0);
    await address.selectOption(custom);
    await preview.getByText('Lead form preview · submissions disabled').waitFor();
    await button('Add image').click();
    const photo=blocks.last(),alt='Fictional product clinic stage';
    const png=await page.evaluate(()=>{
      const canvas=document.createElement('canvas');
      canvas.width=2400;canvas.height=1200;
      const ctx=canvas.getContext('2d');
      ctx.fillStyle='#17696b';ctx.fillRect(0,0,2400,1200);
      return canvas.toDataURL('image/png').split(',')[1];
    });
    await photo.getByLabel('Choose picture').setInputFiles({name:'clinic.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')});
    await photo.getByLabel('Replace picture').waitFor();
    await photo.getByLabel('Alt text').fill(alt);
    await photo.getByLabel('Caption (optional)').fill('November clinic');
    const previewImage=preview.getByRole('img',{name:alt,exact:true});
    await previewImage.waitFor();
    await previewImage.evaluate(img=>img.decode());
    assert.equal(await previewImage.evaluate(img=>img.naturalWidth),1600);
    await photo.getByLabel('Replace picture').setInputFiles({name:'invalid.png',mimeType:'image/png',buffer:Buffer.from('Not a picture')});
    await page.getByRole('alert').filter({hasText:'Choose a JPEG, PNG or WebP picture.'}).waitFor();
    assert.equal(await previewImage.evaluate(img=>img.naturalWidth),1600);
    await button('Save draft').click();
    await page.getByText('Draft saved.',{exact:true}).waitFor();
    const url=custom+'/product-clinic';
    assert.equal((await visitor.goto(url)).status(),404);
    await page.reload();
    assert.deepEqual(await blocks.locator('strong').allTextContents(),['Call to action','Paragraph','Heading','Two columns','Lead form','Call to action','Image']);
    await button('Publish saved page').click();
    await page.getByText('Page published.',{exact:true}).waitFor();
    assert.equal((await visitor.goto(url)).status(),200);
    const image=visitor.getByRole('img',{name:alt,exact:true});
    await image.evaluate(img=>img.decode());
    assert.deepEqual(await image.evaluate(img=>[img.naturalWidth,img.naturalHeight,img.src.startsWith('data:image/jpeg;base64,')]),[1600,800,true]);
    await visitor.locator('figcaption',{hasText:'November clinic'}).waitFor();
    const columns=visitor.locator('.columns > div');
    const [left,right]=await Promise.all([columns.first().boundingBox(),columns.last().boundingBox()]);
    assert.ok(right.x>=left.x+left.width&&right.y===left.y);
    assert.deepEqual(await visitor.locator('main h2').allTextContents(),['Choose a session','Morning session','Afternoon session','Register for the clinic']);
    await visitor.setViewportSize({width:375,height:812});
    const imageBox=await image.boundingBox();
    assert.ok(imageBox.width<=375&&imageBox.height===imageBox.width/2);
    const [top,bottom]=await Promise.all([columns.first().boundingBox(),columns.last().boundingBox()]);
    assert.ok(bottom.y>=top.y+top.height&&bottom.x===top.x);
    assert.ok(await visitor.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    async function submit(email){
      const form=visitor.frameLocator('iframe[title="Register for the clinic"]');
      await form.getByLabel('Name',{exact:true}).fill('Fictional clinic visitor');
      await form.getByLabel('Email address').fill(email);
      await form.getByRole('button',{name:'Send inquiry'}).click();
      await form.getByText('Thank you. Your inquiry has been received.').waitFor();
    }
    await visitor.getByRole('link',{name:'Jump to registration'}).click();
    await visitor.locator(':target').getByRole('heading',{name:'Register for the clinic'}).waitFor();
    assert.equal(await visitor.getByRole('link',{name:'Book a demo'}).getAttribute('href'),bookingUrl);
    await visitor.route(url=>url.hostname==='booking.example.test',route=>route.fulfill({
      contentType:'text/html; charset=utf-8',body:'<!doctype html><title>Fictional demo calendar</title><h1>Fictional demo calendar</h1>',
    }));
    const bookDemo=visitor.getByRole('link',{name:'Book a demo'});
    await bookDemo.scrollIntoViewIfNeeded();
    await Promise.all([visitor.waitForURL(url=>url.href===bookingUrl),bookDemo.click()]);
    assert.equal(visitor.url(),bookingUrl);
    assert.equal(await visitor.title(),'Fictional demo calendar');
    await visitor.goBack();
    await submit('clinic-private@example.test');
    await visitor.goto(url+'?utm_source=clinic-newsletter');
    const consent=visitor.getByRole('button',{name:'Allow visit measurement'});
    await consent.scrollIntoViewIfNeeded();
    await consent.click();
    await visitor.getByRole('button',{name:'Stop visit measurement'}).waitFor({timeout:8000});
    await submit('clinic-subscriber@example.test');
    assert.equal(new URL(visitor.url()).pathname,'/product-clinic');
    await visitor.goto(origin+base+'product-clinic');
    assert.equal(await visitor.locator('iframe').count(),0);
    assert.equal(await visitor.getByRole('link',{name:'Register for the clinic'}).getAttribute('href'),origin+'/forms/'+inlineForm);
    await visitor.goto(url);
    await second.getByLabel('Heading').fill('Evening session');
    const newAlt='Fictional evening clinic stage';
    const replacement=await page.evaluate(()=>{
      const canvas=document.createElement('canvas');
      canvas.width=600;canvas.height=400;
      const ctx=canvas.getContext('2d');ctx.fillStyle='#543';ctx.fillRect(0,0,600,400);
      return canvas.toDataURL('image/jpeg').split(',')[1];
    });
    await photo.getByLabel('Replace picture').setInputFiles({name:'evening.jpg',mimeType:'image/jpeg',buffer:Buffer.from(replacement,'base64')});
    await photo.getByLabel('Alt text').fill(newAlt);
    await preview.getByRole('img',{name:newAlt}).evaluate(async img=>{await img.decode();if(img.naturalWidth!==600)throw Error('Wrong replacement');});
    const listingTitle='Customer clinic | November', listingDescription='Appointments for partners & customers.';
    await page.getByText('Search and link previews',{exact:true}).click();
    await page.getByLabel('Search title',{exact:true}).fill(listingTitle);
    await page.getByLabel('Search description',{exact:true}).fill(listingDescription);
    await page.getByLabel('Ask search engines').check();
    await page.getByText('Previous page addresses',{exact:true}).click();
    await page.getByLabel('Previous addresses (one per line)').fill('fall-clinic');

    await button('Save draft').click();
    await page.getByText('Draft saved.',{exact:true}).waitFor();
    await visitor.reload();
    await visitor.getByRole('heading',{name:'Afternoon session'}).waitFor();
    assert.equal(await visitor.title(),'November product clinic');
    assert.equal(await image.evaluate(async img=>{await img.decode();return img.naturalWidth;}),1600);
    assert.equal(await visitor.getByRole('img',{name:newAlt}).count(),0);
    assert.equal(await visitor.locator('meta[name=robots]').count(),0);
    assert.equal((await fetch(custom+'/fall-clinic')).status,404);
    await verifyDuplicate(page,browser,origin,custom,inlineForm);
    await button('Publish saved page').click();
    await page.getByText('Page published.',{exact:true}).waitFor();
    await visitor.reload();
    await visitor.getByRole('heading',{name:'Evening session'}).waitFor();
    assert.equal((await fetch(custom+'/fall-clinic?utm_source=partner',{redirect:'manual'})).headers.get('location'),'/product-clinic?utm_source=partner');
    await visitor.getByRole('heading',{name:'November product clinic',exact:true}).waitFor();
    assert.equal(await visitor.title(),listingTitle);
    const publishedPhoto=visitor.getByRole('img',{name:newAlt,exact:true});
    assert.equal(await publishedPhoto.evaluate(async img=>{await img.decode();return img.naturalWidth;}),600);
    assert.equal(await visitor.locator('meta[property="og:title"]').getAttribute('content'),listingTitle);
    for(const property of ['meta[name=description]','meta[property="og:description"]']){
      assert.equal(await visitor.locator(property).getAttribute('content'),listingDescription);
    }
    assert.equal(await visitor.locator('meta[name=robots]').getAttribute('content'),'noindex');
    for(const address of [url+'?utm_source=event',origin+base+'product-clinic']){
      const head=await context.request.head(address);
      assert.equal(head.headers()['x-robots-tag'],'noindex');
      await visitor.goto(address);
      assert.equal(await visitor.locator('link[rel=canonical]').getAttribute('href'),url);
      assert.equal(await visitor.locator('meta[property="og:url"]').getAttribute('content'),url);
    }
    await visitor.goto(url);
    await stopEmbedding();
    const fallback=await visitor.reload();
    assert.ok(!fallback.headers()['content-security-policy'].includes('frame-src'));
    assert.equal(await visitor.locator('iframe').count(),0);
    await visitor.getByRole('link',{name:'Register for the clinic'}).waitFor();
    await page.getByLabel('Introduction').fill('Unsaved preview copy');
    await button('Refresh form settings').click();
    await preview.locator('span.cta',{hasText:'Register for the clinic'}).waitFor();
    await closeForm();
    await button('Refresh form settings').click();
    await preview.getByText('Register for the clinic',{exact:true}).waitFor({state:'detached'});
    assert.equal(await preview.getByText('Jump to registration',{exact:true}).count(),0);
    await preview.getByText('Book a demo',{exact:true}).waitFor();
    await preview.getByText('Unsaved preview copy').waitFor();
    assert.equal(await preview.locator('.lead-capture, a, iframe, script').count(),0);
    assert.equal(await page.getByLabel('Introduction').inputValue(),'Unsaved preview copy');
    await visitor.reload();
    assert.equal(await visitor.getByText('Register for the clinic').count(),0);
    assert.equal(await visitor.getByRole('link',{name:'Jump to registration'}).count(),0);
    await visitor.getByRole('link',{name:'Book a demo'}).waitFor();
    await page.getByLabel('Introduction').fill('');
    await button('Withdraw page').click();
    await page.getByText('Page withdrawn.',{exact:true}).waitFor();
    assert.equal((await visitor.reload()).status(),404);
  }finally{await browser.close();}
}

async function verifyDuplicate(source,browser,origin,custom,inlineForm){
  const visitor=await browser.newPage();
  const editor=await source.context().newPage();
  const list=origin+'/?view=landing-pages',sourceId=new URL(source.url()).searchParams.get('edit');
  await editor.goto(list);
  await editor.getByRole('link',{name:'Duplicate draft of November product clinic',exact:true}).click();
  await editor.getByRole('heading',{name:'Duplicate landing page'}).waitFor();
  assert.equal(await editor.getByLabel('Page address').inputValue(),'');
  assert.equal(await editor.getByLabel('Page title').inputValue(),'November product clinic');
  assert.equal(await editor.getByRole('group',{name:'Second column'}).getByLabel('Heading').inputValue(),'Evening session');
  assert.equal(await editor.getByLabel('Display form').inputValue(),'inline');
  assert.equal(await editor.getByRole('combobox',{name:/^Lead form/}).inputValue(),inlineForm);
  await editor.getByText('Search and link previews',{exact:true}).click();
  assert.equal(await editor.getByLabel('Search title',{exact:true}).inputValue(),'Customer clinic | November');
  await editor.getByLabel('Search title',{exact:true}).fill('');
  await editor.getByLabel('Ask search engines').uncheck();
  await editor.getByLabel('Page title').fill('December product clinic');
  await editor.getByText('Previous page addresses',{exact:true}).click();
  assert.equal(await editor.getByLabel('Previous addresses (one per line)').inputValue(),'');
  await editor.getByLabel('Page address').fill('december-clinic');
  await editor.getByRole('button',{name:'Save draft'}).click();
  await editor.getByText('Draft saved.',{exact:true}).waitFor();
  assert.notEqual(new URL(editor.url()).searchParams.get('edit'),sourceId);
  assert.equal(new URL(editor.url()).searchParams.has('copy'),false);
  assert.equal((await visitor.goto(custom+'/december-clinic')).status(),404);
  await editor.reload();
  await editor.getByRole('button',{name:'Publish saved page'}).click();
  await editor.getByText('Page published.',{exact:true}).waitFor();
  assert.equal((await visitor.goto(custom+'/december-clinic')).status(),200);
  await visitor.getByRole('heading',{name:'December product clinic'}).waitFor();
  assert.equal(await visitor.title(),'December product clinic');
  assert.equal(await visitor.locator('meta[name=robots]').count(),0);
  assert.equal(await visitor.locator('link[rel=canonical]').getAttribute('href'),custom+'/december-clinic');
  await visitor.getByRole('img',{name:'Fictional evening clinic stage'}).evaluate(img=>img.decode());
  const form=visitor.frameLocator('iframe[title="Register for the clinic"]');
  await form.getByLabel('Name',{exact:true}).fill('Fictional December visitor');
  await form.getByLabel('Email address').fill('december-visitor@example.test');
  await form.getByRole('button',{name:'Send inquiry'}).click();
  await form.getByText('Thank you. Your inquiry has been received.').waitFor();
  await editor.getByLabel('Page address').fill('december-workshop');
  await editor.getByRole('button',{name:'Keep /december-clinic working'}).click();
  await editor.getByRole('button',{name:'Save draft'}).click();
  await editor.getByText('Draft saved.',{exact:true}).waitFor();
  await editor.getByRole('button',{name:'Publish saved page'}).click();
  await editor.getByText('Page published.',{exact:true}).waitFor();
  await visitor.goto(custom+'/december-clinic?utm_source=partner#agenda');
  assert.equal(visitor.url(),custom+'/december-workshop?utm_source=partner#agenda');
  await editor.getByRole('button',{name:'Withdraw page'}).click();
  await editor.getByText('Page withdrawn.',{exact:true}).waitFor();
  assert.equal((await visitor.reload()).status(),404);
  assert.equal((await visitor.goto(custom+'/product-clinic')).status(),200);
  await visitor.getByRole('heading',{name:'Afternoon session'}).waitFor();
  await visitor.close();
  await editor.close();
}
