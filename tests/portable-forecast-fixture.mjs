import assert from 'node:assert/strict';

export async function verifyForecast({browser,page,origin,owner,other,rep,ownerId,workspaceId,changeGrant,write,request,sql}){
  await changeGrant({action:'role',role:'editor'});
  const month='2031-04';
  const context=await browser.newContext();
  const [name,value]=owner.cookie.split('=');
  await context.addCookies([{name,value,url:origin}]);
  try{
    const manager=await context.newPage();
    const seed=(name,stage,amount,assigneeId,closeDate=month+'-06')=>write('/api/crm',{
      kind:'deals',action:'save',assigneeId,data:{name,stage,amount,closeDate},
    });
    await seed('April open deal','Qualified to buy',250,rep);
    await seed('April sale','Closed won',105,rep);
    await seed('Other owner sale','Closed won',800,ownerId);
    await seed('Unassigned April sale','Closed won',10,null);
    await seed('Lost sale','Closed lost',400,rep);
    await seed('May sale','Closed won',360,rep,'2031-05-06');
    const scope={month,owner:rep,pipelineId:'default'};
    const goals='/?'+new URLSearchParams({view:'goals',...scope});
    const card=(p,label)=>p.locator('.forecast-cards div').filter({has:p.getByText(label,{exact:true})}).locator('dd');
    const breakdown=p=>p.getByRole('table',{name:'Forecast by deal owner'});
    const ownerRow=(p,id)=>breakdown(p).getByRole('row').filter({has:p.locator('a[href*="owner='+id+'"]')});
    await manager.goto(origin+'/?view=forecast&month='+month);
    assert.deepEqual(await ownerRow(manager,rep).getByRole('cell').allTextContents(),['105.00','100.00','205.00']);
    assert.deepEqual(await ownerRow(manager,ownerId).getByRole('cell').allTextContents(),['800.00','0.00','800.00']);
    assert.deepEqual(await breakdown(manager).getByRole('row',{name:/Unassigned/}).getByRole('cell').allTextContents(),['10.00','0.00','10.00']);
    assert.equal(await card(manager,'Forecast including closed won').innerText(),'1,015.00');
    await ownerRow(manager,rep).getByRole('link').click();
    assert.equal(await breakdown(manager).count(),0);
    assert.equal(await card(manager,'Closed won').innerText(),'105.00');
    await manager.goto(origin+goals);
    assert.equal(await card(manager,'Forecast including closed won').innerText(),'205.00');
    await manager.getByLabel('Monthly revenue goal').fill('500.50');
    await manager.getByRole('button',{name:'Save goal'}).click();
    await card(manager,'Revenue goal').getByText('500.50',{exact:true}).waitFor();
    const post=(params,body,auth=owner)=>request('/api/forecast-targets'+params,{method:'POST',
      headers:{...auth,origin,'content-type':'application/json'},body:JSON.stringify(body)});
    assert.equal((await post('',{...scope,revision:0,amountCents:1})).status,409);
    assert.equal((await post('?workspaceId='+workspaceId,{...scope,revision:1,amountCents:0},other)).status,403);
    await manager.getByRole('link',{name:'Forecast',exact:true}).filter({visible:true}).first().click();
    await manager.getByText('395.50 remaining to goal · 21% achieved').waitFor();
    await manager.getByText('295.50 below goal at forecast').waitFor();
    for(const [stage,deal] of [['Closed won','April sale'],['Qualified to buy','April open deal']]){
      await manager.getByRole('rowheader',{name:stage,exact:true}).getByRole('link').click();
      assert.equal(new URL(manager.url()).searchParams.get('owner'),rep);
      await manager.getByRole('link',{name:deal,exact:true}).waitFor();
      assert.equal(await manager.getByText('Other owner sale',{exact:true}).count(),0);
      assert.equal(await manager.getByText('May sale',{exact:true}).count(),0);
      await manager.goBack();
    }
    await changeGrant({action:'role',role:'viewer'});
    await page.goto(origin+'/?view=forecast&workspaceId='+workspaceId+'&month='+month);
    assert.deepEqual(await breakdown(page).getByRole('row',{name:/Unavailable owners/}).getByRole('cell').allTextContents(),['105.00','100.00','205.00']);
    await page.getByRole('combobox',{name:/^Deal owner/}).selectOption(ownerId);
    await page.getByRole('button',{name:'Apply'}).click();
    assert.equal(await card(page,'Closed won').innerText(),'800.00');
    await changeGrant({action:'role',role:'editor'});
    await changeGrant({action:'record_scope',viewScope:'owned',editScope:'owned'});
    const shared=origin+'/?view=forecast&workspaceId='+workspaceId+'&month='+month;
    await page.goto(shared);
    assert.equal(await breakdown(page).getByRole('row').count(),2);
    assert.equal(await ownerRow(page,rep).count(),1);
    assert.equal(await card(page,'Closed won').innerText(),'105.00');
    assert.equal(await card(page,'Revenue goal').count(),0);
    assert.equal(await page.getByRole('combobox',{name:/^Deal owner/}).locator('option[value="'+ownerId+'"]').count(),0);
    await page.getByRole('combobox',{name:/^Deal owner/}).selectOption('mine');
    await page.getByRole('button',{name:'Apply'}).click();
    assert.equal(await card(page,'Revenue goal').innerText(),'500.50');
    assert.equal(await page.getByRole('button',{name:'Save goal'}).count(),0);
    await page.getByRole('rowheader',{name:'Closed won',exact:true}).getByRole('link').click();
    assert.equal(new URL(page.url()).searchParams.get('workspaceId'),workspaceId);
    await page.getByRole('link',{name:'April sale',exact:true}).waitFor();
    await manager.goto(origin+goals.replace(month,'2031-06'));
    assert.equal(await card(manager,'Forecast including closed won').innerText(),'0.00');
    assert.equal(await card(manager,'Revenue goal').innerText(),'No goal set');
    await manager.goto(origin+goals);
    await manager.getByLabel('Monthly revenue goal').fill('');
    await manager.getByRole('button',{name:'Save goal'}).click();
    await card(manager,'Revenue goal').getByText('No goal set',{exact:true}).waitFor();
    assert.equal((await post('',{...scope,revision:0,amountCents:1})).status,409);
    const {pipeline}=await write('/api/pipeline',{name:'Renewals forecast',stages:[
      {name:'Reviewing',outcome:'open',probability:35},{name:'Renewed',outcome:'won'},{name:'Expired',outcome:'lost'}]});
    await write('/api/crm',{action:'save',kind:'deals',pipelineId:pipeline.id,stageId:pipeline.stages[0].id,
      data:{name:'April renewal',amount:330,closeDate:month+'-08'}});
    const renewals={month,pipelineId:pipeline.id,owner:'all'};
    const competing=await Promise.all([20000,30000].map(amountCents=>post('',{...renewals,amountCents,revision:0})));
    assert.deepEqual(competing.map(r=>r.status).sort(),[200,409]);
    assert.equal((await post('',{...renewals,amountCents:1000,revision:0},other)).status,404);
    await manager.goto(origin+'/?'+new URLSearchParams({kind:'deals',view:'summary',pipelineId:pipeline.id,closeMonth:month}));
    await manager.getByRole('link',{name:'Open monthly forecast'}).click();
    assert.equal(new URL(manager.url()).searchParams.get('month'),month);
    assert.equal(await card(manager,'Forecast including closed won').innerText(),'115.50');
    assert.equal(await card(manager,'Revenue goal').innerText(),competing[0].ok?'200.00':'300.00');
    await manager.getByRole('rowheader',{name:'Reviewing',exact:true}).getByRole('link').click();
    await manager.getByRole('link',{name:'April renewal',exact:true}).waitFor();
    assert.equal(new URL(manager.url()).searchParams.get('pipelineId'),pipeline.id);
    await verifyFiscalQuarter({manager,page,seed,origin,rep,ownerId,workspaceId,post,card});
    await verifyManagerTeam({manager,page,origin,workspaceId,ownerId,rep,changeGrant,write,seed,sql,breakdown,ownerRow,card});
    for(const field of ['amount','closeDate']){
      const policy=(audience,expectedRevision)=>write('/api/custom-properties',{action:'standardAccess',kind:'deals',id:field,audience,expectedRevision});
      const {property}=await policy('owner',0);
      await page.goto(shared+'&owner=mine');
      await page.getByText('Viewing a revenue forecast requires access to Deal amount and Close date.').waitFor();
      assert.equal(await page.locator('.forecast-cards').count(),0);
      await page.goto(origin+'/?kind=deals&workspaceId='+workspaceId);
      await page.getByRole('button',{name:'Open navigation'}).click();
      const nav=page.getByRole('navigation',{name:'Main navigation'});
      for(const [section,label] of [['Sales','Forecast'],['Reporting','Goals']]){
        await nav.getByRole('button',{name:section,exact:true}).click();
        assert.equal(await nav.getByRole('link',{name:label,exact:true}).count(),0);
      }
      await policy('workspace',property.revision);
    }
  }finally{await context.close();}
}

async function verifyManagerTeam({manager,page,origin,workspaceId,ownerId,rep,changeGrant,write,seed,sql,breakdown,ownerRow,card}){
  const manage=body=>write('/api/workspaces',body);
  const email='owner@example.test';
  const [{id:childRep}]=await sql`SELECT id FROM login_identities WHERE email=${email}`;
  const parent=crypto.randomUUID(),child=crypto.randomUUID();
  for(const [id,name,parentId] of [[parent,'Forecast region',null],[child,'Forecast district',parent]]){
    await manage({action:'team_create',id,name,parentId});
  }
  const directory=await manage({action:'grant',email});
  const promoted=await manage({action:'role',id:directory.viewers.find(row=>row.email===email).id,role:'editor'});
  const grant=promoted.viewers.find(row=>row.email===email).id;
  await manage({action:'team_assign',id:grant,teamId:child,previousTeamId:null});
  await changeGrant({action:'team_assign',teamId:parent,previousTeamId:null});
  await changeGrant({action:'record_scope',viewScope:'team',editScope:'owned'});
  await seed('Regional renewal','Closed won',25,rep,'2033-08-09');
  await seed('District renewal','Closed won',50,childRep,'2033-08-10');
  await seed('Regional open adjustment','Qualified to buy',0.01,rep,'2033-08-09');
  await seed('District open adjustment','Qualified to buy',0.01,childRep,'2033-08-10');
  await seed('Other region renewal','Closed won',100,ownerId,'2033-08-11');
  await seed('Unassigned forecast inquiry','Closed won',17,null,'2033-08-12');
  await manager.goto(origin+'/?view=forecast&month=2033-08');
  const full=manager.getByRole('table',{name:'Forecast by primary team'});
  assert.equal(await full.getByRole('row').count(),5);
  assert.equal(await full.getByRole('row').filter({hasText:'No primary team'}).getByRole('cell').first().innerText(),'100.00');
  assert.equal(await full.getByRole('row').filter({hasText:'Unassigned deals'}).getByRole('cell').first().innerText(),'17.00');
  const url=origin+'/?view=forecast&workspaceId='+workspaceId+'&month=2033-08';
  await page.goto(url);
  assert.equal(await card(page,'Closed won').innerText(),'75.00');
  assert.equal(await breakdown(page).getByRole('row').count(),3);
  assert.equal(await ownerRow(page,ownerId).count(),0);
  const teams=page.getByRole('table',{name:'Forecast by primary team'});
  const regional=teams.getByRole('row').filter({has:page.getByText('Forecast region',{exact:true})});
  const district=teams.getByRole('row').filter({has:page.getByText('Forecast district',{exact:true})});
  assert.equal(await teams.getByRole('row').count(),3);
  assert.deepEqual(await regional.getByRole('cell').allTextContents(),['25.00','0.00','25.00'],await teams.innerText());
  assert.deepEqual(await district.getByRole('cell').allTextContents(),['50.00','0.00','50.00']);
  await page.goto(url+'&period=quarter');
  await district.locator('summary').click();
  await district.getByRole('link').click();
  const selected=new URL(page.url()).searchParams;
  assert.equal(selected.get('period'),'quarter');
  assert.equal(selected.get('workspaceId'),workspaceId);
  assert.equal(selected.get('owner'),childRep);
  assert.equal(await card(page,'Closed won').innerText(),'50.00');
  const savedUrl=page.url();
  await manage({action:'team_assign',id:grant,teamId:parent,previousTeamId:child});
  await page.goto(url);
  assert.equal(await district.count(),0);
  assert.deepEqual(await regional.getByRole('cell').allTextContents(),['75.00','0.01','75.01']);
  await manage({action:'team_assign',id:grant,teamId:null,previousTeamId:parent});
  const removed=await page.goto(savedUrl);
  assert.equal(removed.status(),404);
  await page.goto(url);
  assert.equal(await card(page,'Closed won').innerText(),'25.00');
  assert.equal(await ownerRow(page,childRep).count(),0);
  assert.equal(await district.count(),0);
  assert.deepEqual(await regional.getByRole('cell').allTextContents(),['25.00','0.00','25.00'],await teams.innerText());
}

async function verifyFiscalQuarter({manager,page,seed,origin,rep,ownerId,workspaceId,post,card}){
  await seed('November opportunity','Qualified to buy',200,rep,'2031-11-01');
  await seed('December sale','Closed won',125,rep,'2031-12-31');
  await seed('January sale','Closed won',25,rep,'2032-01-31');
  await seed('February sale','Closed won',900,rep,'2032-02-01');
  await seed('Separate owner sale','Closed won',350,ownerId,'2031-12-15');
  const scope={pipelineId:'default',owner:rep};
  const path=params=>origin+'/?'+new URLSearchParams({view:'goals',...scope,...params});
  await manager.goto(path({month:'2032-01'}));
  await manager.getByText('Workspace fiscal calendar',{exact:true}).click();
  await manager.getByLabel('Fiscal year starts in').selectOption('11');
  await Promise.all([manager.waitForNavigation(),manager.getByRole('button',{name:'Save calendar'}).click()]);
  const period=manager.getByRole('combobox',{name:/^Period/});
  assert.equal(await period.count(),1,(await manager.locator('main').innerText()).slice(0,1200));
  await period.selectOption('quarter');
  await manager.getByRole('button',{name:'Apply'}).click();
  await manager.getByRole('heading',{name:'FQ1 FY 2031–2032 · 2031-11 through 2032-01'}).waitFor();
  assert.equal(await card(manager,'Closed won').innerText(),'150.00');
  assert.equal(await card(manager,'Forecast including closed won').innerText(),'230.00');
  await manager.getByLabel('Quarterly revenue goal').fill('400');
  await manager.getByRole('button',{name:'Save goal'}).click();
  await card(manager,'Revenue goal').getByText('400.00',{exact:true}).waitFor();
  const monthly={...scope,month:'2031-11',revision:0,amountCents:5000};
  assert.equal((await post('',monthly)).status,200);
  await manager.goto(path({month:'2031-11'}));
  assert.equal(await card(manager,'Revenue goal').innerText(),'50.00');
  const quarter={period:'quarter',month:'2031-12'};
  await manager.goto(path(quarter));
  assert.equal(await card(manager,'Revenue goal').innerText(),'400.00');
  await page.goto(path({...quarter,view:'forecast',workspaceId,owner:'all'}));
  const comparison=page.getByRole('table',{name:'Forecast by deal owner'});
  assert.equal(await comparison.getByRole('row').count(),2);
  assert.deepEqual(await comparison.getByRole('cell').allTextContents(),['150.00','80.00','230.00']);
  await comparison.getByRole('link').click();
  const drill=new URL(page.url()).searchParams;
  for(const [key,value] of Object.entries({...quarter,workspaceId,owner:rep,pipelineId:'default'}))assert.equal(drill.get(key),value);
  assert.equal(await card(page,'Closed won').innerText(),'150.00');
  assert.equal(await card(page,'Revenue goal').innerText(),'400.00');
  const won=page.locator('details').filter({has:page.locator('summary').filter({hasText:/^Closed won$/})});
  await won.locator('summary').click();
  assert.deepEqual(await won.getByRole('link').allTextContents(),['2031-11 · 0 deals','2031-12 · 1 deal','2032-01 · 1 deal']);
  await won.getByRole('link',{name:'2031-12 · 1 deal'}).click();
  await page.getByRole('link',{name:'December sale',exact:true}).waitFor();
  assert.equal(new URL(page.url()).searchParams.get('workspaceId'),workspaceId);
  assert.equal(await page.getByRole('link',{name:'Separate owner sale',exact:true}).count(),0);
  assert.equal(await page.getByRole('link',{name:'January sale',exact:true}).count(),0);
  const calendar=(expectedStart,start)=>post('',{action:'set_calendar',expectedStart,start});
  assert.equal((await calendar(1,4)).status,409);
  const oldQuarter={...scope,period:'quarter',fiscalStartMonth:'11',revision:0};
  assert.equal((await post('',{...oldQuarter,month:'2031-08',amountCents:0})).status,200);
  assert.equal((await post('',{...oldQuarter,month:'2031-11',owner:ownerId,amountCents:98765})).status,200);
  assert.equal((await post('',{...oldQuarter,month:'2031-11',owner:'all',amountCents:200000})).status,200);
  await manager.getByText('Workspace fiscal calendar',{exact:true}).click();
  const calendarEditor=manager.locator('details').filter({has:manager.locator('summary').filter({hasText:'Workspace fiscal calendar'})});
  await calendarEditor.getByLabel('Fiscal year starts in').selectOption('2');
  assert.equal(await calendarEditor.getByRole('status').count(),0);
  await calendarEditor.getByLabel('Fiscal year starts in').selectOption('1');
  await calendarEditor.getByRole('status').filter({hasText:'changes which months'}).waitFor();
  await Promise.all([manager.waitForNavigation(),calendarEditor.getByRole('button',{name:'Save calendar'}).click()]);
  assert.equal((await post('',{...monthly,...quarter,revision:1})).status,400);
  assert.equal((await post('',{...monthly,...quarter,revision:1,fiscalStartMonth:'11'})).status,409);
  await manager.goto(path(quarter));
  assert.equal(await card(manager,'Revenue goal').innerText(),'No goal set');
  const earlier=p=>p.getByRole('region',{name:'Goals from earlier calendars'});
  assert.deepEqual(await earlier(manager).locator('dt').allTextContents(),['2031-08 through 2031-10','2031-11 through 2032-01']);
  assert.deepEqual(await earlier(manager).locator('dd').allTextContents(),['0.00','400.00']);
  await manager.goto(path({...quarter,owner:'all'}));
  assert.deepEqual(await earlier(manager).locator('dd').allTextContents(),['2,000.00']);
  await manager.goto(path(quarter));
  await page.goto(path({...quarter,workspaceId,owner:'mine',month:'2032-02'}));
  assert.deepEqual(await earlier(page).locator('dt').allTextContents(),['2031-11 through 2032-01']);
  assert.deepEqual(await earlier(page).locator('dd').allTextContents(),['400.00']);
  await page.goto(path({...quarter,workspaceId,owner:'all'}));
  assert.equal(await earlier(page).count(),0);
  assert.equal(await card(page,'Revenue goal').count(),0);
  await manager.getByLabel('Quarterly revenue goal').fill('600');
  await manager.getByRole('button',{name:'Save goal'}).click();
  await card(manager,'Revenue goal').getByText('600.00',{exact:true}).waitFor();
  assert.deepEqual(await earlier(manager).locator('dd').allTextContents(),['0.00','400.00']);
  assert.equal((await calendar(1,11)).status,200);
  await manager.reload();
  assert.equal(await card(manager,'Revenue goal').innerText(),'400.00');
  assert.deepEqual(await earlier(manager).locator('dd').allTextContents(),['600.00']);
}
